-- ==============================================================================
-- 1. FUNCIÓN REUTILIZABLE PARA ACTUALIZAR EL CAMPO updated_at
-- ==============================================================================
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ==============================================================================
-- 2. TABLAS MAESTRAS (CATÁLOGOS BASE)
-- ==============================================================================

CREATE TABLE public.maquinas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.area_impacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.referencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion TEXT NOT NULL,
    num_colores INT,
    display INT,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.turno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    descripcion TEXT,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.tipo_agente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);


-- ==============================================================================
-- 3. CATÁLOGOS DEPENDIENTES (CON CLAVES FORÁNEAS)
-- ==============================================================================

CREATE TABLE public.codigo_paro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL,
    descripcion TEXT,
    fk_area_impacto BIGINT REFERENCES public.area_impacto(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.subcodigo_paro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL,
    descripcion TEXT,
    fk_codigo_paro BIGINT REFERENCES public.codigo_paro(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.agente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_tipo_agente BIGINT REFERENCES public.tipo_agente(id) ON DELETE RESTRICT,
    nombre TEXT NOT NULL,
    documento TEXT,
    telefono TEXT,
    correo TEXT,
    sexo TEXT,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.produccion_referencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fk_maquina BIGINT REFERENCES public.maquinas(id) ON DELETE RESTRICT,
    fk_referencia BIGINT REFERENCES public.referencia(id) ON DELETE RESTRICT,
    pacas NUMERIC(10,2),
    ud_paca INT,
    ud_minuto NUMERIC(10,2),
    horas_trabajadas NUMERIC(5,2),
    minutos_turno NUMERIC(10,2),
    ud_ideales_turno NUMERIC(10,2),
    pacas_ideales_turno NUMERIC(10,2),
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);


-- ==============================================================================
-- 4. TABLAS TRANSACCIONALES (HECHOS Y DETALLE DE PAROS)
-- ==============================================================================

CREATE TABLE public.registros_produccion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL,
    fk_maquina BIGINT REFERENCES public.maquinas(id) ON DELETE RESTRICT,
    fk_agente BIGINT REFERENCES public.agente(id) ON DELETE RESTRICT,
    fk_referencia BIGINT REFERENCES public.referencia(id) ON DELETE RESTRICT,
    fk_turno BIGINT REFERENCES public.turno(id) ON DELETE RESTRICT,
    pacas_producidas NUMERIC(10,2) DEFAULT 0,
    pacas_defectuosas NUMERIC(10,2) DEFAULT 0,
    ud_producidas_minuto NUMERIC(10,2) DEFAULT 0,
    horas_trabajadas NUMERIC(5,2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

CREATE TABLE public.registros_paro (
    id SERIAL PRIMARY KEY,
    fk_registro_produccion INT REFERENCES public.registros_produccion(id) ON DELETE CASCADE,
    fk_codigo_paro INT REFERENCES public.codigo_paro(id),        
    fk_subcodigo_paro INT REFERENCES public.subcodigo_paro(id), 
    tiempo_paro_minutos NUMERIC,
    observaciones TEXT,
    hash_evento TEXT UNIQUE,
    created_at TIMESTAMPTZ DEFAULT now() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT now() NOT NULL
);

-- ==============================================================================
-- 5. AUTOMATIZACIÓN DE AUDITORÍA (TRIGGERS UPDATED_AT)
-- ==============================================================================

CREATE TRIGGER tr_updated_at_maquinas BEFORE UPDATE ON public.maquinas FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_area_impacto BEFORE UPDATE ON public.area_impacto FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_referencia BEFORE UPDATE ON public.referencia FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_turno BEFORE UPDATE ON public.turno FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_tipo_agente BEFORE UPDATE ON public.tipo_agente FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_codigo_paro BEFORE UPDATE ON public.codigo_paro FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_subcodigo_paro BEFORE UPDATE ON public.subcodigo_paro FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_agente BEFORE UPDATE ON public.agente FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_produccion_referencia BEFORE UPDATE ON public.produccion_referencia FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_registros_produccion BEFORE UPDATE ON public.registros_produccion FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
CREATE TRIGGER tr_updated_at_registros_paro BEFORE UPDATE ON public.registros_paro FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();


-- ==============================================================================
-- 6. ÍNDICES DE RENDIMIENTO (OPTIMIZACIÓN DE CONSULTAS Y JOINS)
-- ==============================================================================

CREATE INDEX idx_codigo_paro_area ON public.codigo_paro(fk_area_impacto);
CREATE INDEX idx_subcodigo_paro_codigo ON public.subcodigo_paro(fk_codigo_paro);
CREATE INDEX idx_agente_tipo ON public.agente(fk_tipo_agente);
CREATE INDEX idx_produccion_ref_maquina_ref ON public.produccion_referencia(fk_maquina, fk_referencia);

CREATE INDEX idx_registros_prod_fecha ON public.registros_produccion(fecha);
CREATE INDEX idx_registros_prod_maquina ON public.registros_produccion(fk_maquina);
CREATE INDEX idx_registros_prod_agente ON public.registros_produccion(fk_agente);
CREATE INDEX idx_registros_prod_referencia ON public.registros_produccion(fk_referencia);
CREATE INDEX idx_registros_prod_turno ON public.registros_produccion(fk_turno);

CREATE INDEX idx_registros_paro_registro_prod ON public.registros_paro(fk_registro_produccion);
CREATE INDEX idx_registros_paro_subcodigo ON public.registros_paro(fk_subcodigo_paro);


